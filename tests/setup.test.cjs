'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const {createSetup} = require('../src/setup.cjs');

(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'alabaster-setup-test-'));
  const home = path.join(temp, 'home');
  const root = path.join(home, 'Native Launcher');
  const demo = path.join(home, '.local/share/Steam/steamapps/common/Alabaster Dawn Demo');
  const full = path.join(home, '.local/share/Steam/steamapps/common/Alabaster Dawn');
  const passed = [];
  let active = false;
  try {
    await fs.mkdir(path.join(root, 'app'), {recursive:true});
    await fs.mkdir(path.join(root, 'runtime/nwjs-v0.119.2-linux-arm64'), {recursive:true});
    await fs.writeFile(path.join(root, 'runtime/nwjs-v0.119.2-linux-arm64/nw'), 'fixture runtime', {mode:0o700});
    for (const game of [demo,full]) {
      await fs.mkdir(path.join(game, 'terra/dist'), {recursive:true});
      await fs.writeFile(path.join(game, 'package.json'), JSON.stringify({name:'Alabaster Dawn',main:'terra/index.html'}));
      await fs.writeFile(path.join(game, 'terra/dist/bundle.js'), '// fixture');
      await fs.writeFile(path.join(game, 'terra/index.html'), '<!doctype html>' + (game === demo ? '<script>window.XG_DEMO_VERSION = true;</script>' : '') + '<script src="dist/bundle.js"></script>');
    }
    const setup = createSetup({root,home,isBusy:async()=>active});
    let status = await setup.setupStatus();
    assert.equal(status.installed,false);assert.equal(status.defaultGamePath,full);
    passed.push('Fresh setup defaults to the installed full Steam game');
    const updates=[];
    status=await setup.install(demo,x=>updates.push(x));
    assert.equal(status.installed,true);assert.equal(status.edition,'demo');assert.equal(updates.at(-1).percent,100);
    assert.equal(await fs.realpath(path.join(root,'app/terra/dist')),path.join(demo,'terra/dist'));
    passed.push('Installation links original data and leaves source files unchanged');
    active=true;
    await assert.rejects(setup.uninstall(),/Close both versions/);
    active=false;
    passed.push('Running-game guard prevents uninstall');
    await fs.mkdir(path.join(root,'profile'),{recursive:true});
    const save=path.join(root,'profile','Default\\Saves\\Default\\Save_ID_0001.save');
    await fs.writeFile(save,'untouched saved progress');
    await setup.uninstall();
    assert.equal((await setup.setupStatus()).installed,false);
    assert.equal(await fs.readFile(save,'utf8'),'untouched saved progress');
    assert.equal(await fs.readFile(path.join(demo,'terra/dist/bundle.js'),'utf8'),'// fixture');
    passed.push('Uninstall preserves original game and native saves');
    await assert.rejects(setup.install(full),/another edition/);
    assert.equal(await fs.readFile(save,'utf8'),'untouched saved progress');
    passed.push('Demo and full-game progress cannot be mixed by reinstall');
    await setup.install(demo);
    assert.equal((await setup.setupStatus()).installed,true);
    passed.push('Same-edition reinstall preserves existing progress');
    await assert.rejects(setup.install(root),/original Steam game folder/);
    assert.equal((await setup.setupStatus()).installed,true);
    passed.push('Invalid source selection leaves the current installation intact');
    const clean = path.join(home,'Full Launcher');
    await fs.cp(root,clean,{recursive:true});
    await fs.rm(path.join(clean,'profile'),{recursive:true});
    await fs.rm(path.join(clean,'app/terra'),{recursive:true});
    await fs.rm(path.join(clean,'setup.json'));
    await fs.rm(path.join(clean,'profile-edition.json'));
    const fullSetup=createSetup({root:clean,home});
    await fullSetup.install(full);
    assert.equal(fullSetup.getContext().variant,'full');
    assert.equal(fullSetup.getContext().steamProfile,path.join(home,'.config/Alabaster Dawn'));
    passed.push('Full edition binds to an independent fresh native profile');
    await fullSetup.install(full,()=>{throw new Error('UI callback failed');});
    assert.equal(fullSetup.getContext().variant,'full');
    passed.push('UI progress errors cannot undo a committed installation');
    const relocated=full+' moved';
    await fs.rename(full,relocated);
    assert.equal((await fullSetup.setupStatus()).installed,false);
    await fullSetup.install(relocated);
    assert.equal(fullSetup.getContext().gameDir,relocated);
    passed.push('Moved Steam game can be rebound through Install');
    await fs.rename(relocated,full);
    await fullSetup.uninstall();
    assert.equal((await fullSetup.setupStatus()).installed,false);
    passed.push('Uninstall works after the original game is moved');
    await fs.rename(path.join(clean,'app'),path.join(clean,'app-before'));
    await fs.symlink(full,path.join(clean,'app'));
    await assert.rejects(fullSetup.uninstall(),/real directory/);
    await assert.rejects(fullSetup.install(full),/real directory/);
    assert.equal(await fs.readFile(path.join(full,'terra/dist/bundle.js'),'utf8'),'// fixture');
    passed.push('Symlinked managed directory cannot redirect deletion to original data');
    console.log(JSON.stringify({passed},null,2));
  } finally { await fs.rm(temp,{recursive:true,force:true}); }
})().catch(error=>{console.error(error);process.exitCode=1;});
